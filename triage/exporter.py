import json
import os
from pathlib import Path
from typing import List, Optional
from triage.models import ParsedRun
from triage.llm.validator import TriageResult, AnalyzedGroup


def export_json(result: TriageResult, run: ParsedRun) -> str:
    """Export triage result and parsed run metadata as JSON."""
    payload = {
        "summary": result.summary,
        "total_failures": len(run.failures),
        "framework": run.framework,
        "duration": run.duration_str,
        "is_fallback": result.is_fallback,
        "provider": result.provider,
        "latency_ms": result.latency_ms,
        "validation_warnings": result.validation_warnings,
        "groups": [g.to_dict() for g in result.groups],
    }
    return json.dumps(payload, indent=2)


def export_markdown(result: TriageResult, run: ParsedRun) -> str:
    """Generate GitHub-flavored Markdown triage report for CI/CD PR comments."""
    lines = [
        "## ⚡ Test Failure Triage Report",
        "",
        f"- **Framework:** `{run.framework.upper()}`",
        f"- **Total Failures:** `{len(run.failures)}`",
        f"- **Root Cause Groups:** `{len(result.groups)}`",
    ]
    if run.duration_str:
        lines.append(f"- **Run Duration:** `{run.duration_str}`")

    if not result.is_fallback and result.provider != "deterministic":
        lines.append(f"- **Mode:** AI Diagnostics (`{result.provider.upper()}` in {int(result.latency_ms)}ms)")
    else:
        lines.append("- **Mode:** Deterministic Rule Engine")

    lines.extend([
        "",
        "### 📊 Root Cause Clusters Summary",
        "",
        "| Group | Priority | Root Cause | Failures | Confidence |",
        "| :---: | :---: | :--- | :---: | :---: |",
    ])

    priority_emojis = {
        "HIGH": "🔴 HIGH",
        "MEDIUM": "🟡 MEDIUM",
        "LOW": "🟢 LOW",
    }

    for g in result.groups:
        badge = priority_emojis.get(g.priority, g.priority)
        lines.append(
            f"| #{g.group_id} | {badge} | {g.root_cause} | {g.count} | {int(g.confidence * 100)}% |"
        )

    lines.extend(["", "### 🔍 Failure Details & Recommended Actions", ""])

    for g in result.groups:
        badge = priority_emojis.get(g.priority, g.priority)
        lines.append(f"#### Group #{g.group_id} — {g.root_cause} ({badge})")
        if g.explanation:
            lines.append(f"> **Why it broke:** {g.explanation}")
            lines.append("")

        if g.suggested_fix:
            lines.append("**Suggested Fix:**")
            lines.append(f"```bash\n{g.suggested_fix}\n```")
            lines.append("")

        lines.append("<details>")
        lines.append(f"<summary><b>Affected Tests ({g.count})</b></summary>")
        lines.append("")
        for tid in g.affected_tests:
            lines.append(f"- `{tid}`")
        lines.append("")
        lines.append("</details>")
        lines.append("")

    return "\n".join(lines)


def export_fix_script(result: TriageResult, file_path: str) -> str:
    """
    Generate an executable fix script (.sh or .ps1) containing all suggested fixes.
    Returns the absolute path of the generated script.
    """
    out_path = Path(file_path).resolve()
    is_powershell = out_path.suffix.lower() == ".ps1" or (os.name == "nt" and out_path.suffix == "")

    if is_powershell and not out_path.suffix:
        out_path = out_path.with_suffix(".ps1")
    elif not is_powershell and not out_path.suffix:
        out_path = out_path.with_suffix(".sh")

    lines = []
    if is_powershell:
        lines.append("# PowerShell Test Fix Automation Script")
        lines.append("# Generated by Triage AI")
        lines.append("$ErrorActionPreference = 'Stop'")
        lines.append("Write-Host 'Applying automated test failure fixes...' -ForegroundColor Cyan")
        lines.append("")
    else:
        lines.append("#!/usr/bin/env bash")
        lines.append("# Bash Test Fix Automation Script")
        lines.append("# Generated by Triage AI")
        lines.append("set -e")
        lines.append("echo 'Applying automated test failure fixes...'")
        lines.append("")

    for g in result.groups:
        if not g.suggested_fix:
            continue

        comment_prefix = "#"
        lines.append(f"{comment_prefix} -------------------------------------------------------------")
        lines.append(f"{comment_prefix} Group #{g.group_id}: {g.root_cause} ({g.priority} Priority)")
        lines.append(f"{comment_prefix} Affected Tests ({g.count}): {', '.join(g.affected_tests[:3])}...")
        lines.append(f"{comment_prefix} -------------------------------------------------------------")

        # Clean commands if there are multi-command suggestions
        fix_lines = [cmd.strip() for cmd in g.suggested_fix.splitlines() if cmd.strip()]
        for cmd in fix_lines:
            # If the suggested fix is plain advice or starts with Check/Inspect, keep as comment
            if any(cmd.lower().startswith(prefix) for prefix in ("check", "inspect", "ensure", "review")):
                lines.append(f"{comment_prefix} Action needed: {cmd}")
            else:
                import re
                clean_cmd = re.sub(r'\(.*?\)', '', cmd).strip()
                if clean_cmd:
                    lines.append(clean_cmd)
                if "(" in cmd:
                    lines.append(f"{comment_prefix} Note: {cmd}")
        lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    return str(out_path)
